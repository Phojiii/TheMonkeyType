export function wordsFor(lang = "english") {
  const bank = TEXTBANKS[lang] || TEXTBANKS.english;
  return bank.join(" ").split(/\s+/u).map((word) => word.trim()).filter(Boolean);
}

const PUNCT = [",", ".", "!", "?", ";", ":", "—"];
const randInt = (min, max) => Math.floor(Math.random() * (max - min + 1)) + min;
const pick = (items) => items[Math.floor(Math.random() * items.length)];

function maybePunct(enable) {
  if (!enable || Math.random() >= 0.18) return "";
  if (Math.random() < 0.6) return pick([",", "."]);
  return pick(PUNCT);
}

function numberToken() {
  const length = randInt(1, 4);
  let value = "";
  for (let index = 0; index < length; index += 1) value += String(randInt(0, 9));
  return value;
}

export function randomParagraph(
  lang = "english",
  { punctuation = false, numbers = false } = {}
) {
  const bank = TEXTBANKS[lang] || TEXTBANKS.english;
  if (!punctuation && !numbers) return pick(bank);
  return makeStreamGenerator({ lang, punctuation, numbers }).nextChunk(60).trim();
}

export function makeStreamGenerator({ lang = "english", punctuation = false, numbers = false } = {}) {
  const words = wordsFor(lang);
  const wordCount = Math.max(1, words.length);

  const nextToken = () => {
    if (numbers && Math.random() < 0.1) return numberToken();
    return words[Math.floor(Math.random() * wordCount)];
  };

  const nextChunk = (count = 60) => {
    const output = new Array(count);
    for (let index = 0; index < count; index += 1) {
      const word = nextToken();
      const punctuationMark = maybePunct(punctuation);
      output[index] = punctuationMark ? `${word}${punctuationMark}` : word;
    }

    let text = output.join(" ");
    if (Math.random() < 0.5) {
      text = text.charAt(0).toUpperCase() + text.slice(1);
      if (!/[.!?]$/u.test(text)) text += ".";
    }
    return `${text} `;
  };

  return { nextChunk };
}